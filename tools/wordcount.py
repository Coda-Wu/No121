# -*- coding: utf-8 -*-
"""Count the spoken-word and diegetic-paper budgets in 70-Script/.

Spoken lines are `**SPEAKER:** text` in files with `type: script`.
Everything else - italic stage directions, HTML comments, prose - is free.
Files with `type: document` are counted separately as diegetic paper.

Run from the vault root:  python tools/wordcount.py
Writes 70-Script/_Word Count.md
"""
import io, os, re, sys, collections

ROOT = "70-Script"
SPOKEN_LOCK = 15000

def words(t):
    t = re.sub(r"<!--.*?-->", " ", t, flags=re.S)
    t = re.sub(r"🔧", " ", t)
    return len([w for w in re.split(r"\s+", t.strip()) if re.search(r"[^\W\d_]", w, re.U)])

def main():
    per_scene, per_card, per_speaker = [], collections.Counter(), collections.Counter()
    paper_scene, paper_card = [], collections.Counter()
    for dp, _, fns in os.walk(ROOT):
        for fn in sorted(fns):
            if not fn.endswith(".md") or fn.startswith("_"):
                continue
            p = os.path.join(dp, fn)
            s = io.open(p, encoding="utf-8").read()
            fm = re.match(r"^---\n(.*?)\n---\n", s, re.S)
            meta, body = (fm.group(1), s[fm.end():]) if fm else ("", s)
            kind = (re.search(r"^type:\s*(\S+)", meta, re.M) or [None, "script"])[1]
            card = (re.search(r'card:\s*"([^"]*)"', meta) or [None, "?"])[1]
            card = card if isinstance(card, str) else "?"
            label = os.path.basename(dp) + " / " + fn[:-3]
            if kind == "document":
                body_clean = re.sub(r"<!--.*?-->", " ", body, flags=re.S)
                body_clean = re.sub(r"^\*.*?\*$", " ", body_clean, flags=re.M)
                n = words(body_clean)
                paper_scene.append((label, n)); paper_card[card] += n
            else:
                n = 0
                for m in re.finditer(r"^\*\*([^*:]+):\*\*(.*)$", body, re.M):
                    c = words(m.group(2))
                    n += c; per_speaker[m.group(1).strip()] += c
                per_scene.append((label, n)); per_card[card] += n
    spoken = sum(n for _, n in per_scene)
    paper = sum(n for _, n in paper_scene)

    L = ["---", "type: report", "status: generated", "---",
         "# Word Count", "",
         "> [!warning] Generated by `tools/wordcount.py`. **Never hand-edit.** Rerun to refresh.", "",
         "## Totals", "",
         "| Budget | Used | Lock | Remaining |", "|---|---|---|---|",
         "| **Spoken** | %d | %d | %d |" % (spoken, SPOKEN_LOCK, SPOKEN_LOCK - spoken),
         "| **Diegetic paper** | %d | 🔧 unset | — |" % paper, "",
         "## Spoken, by card", "", "| Card | Words |", "|---|---|"]
    for c, n in per_card.most_common():
        L.append("| %s | %d |" % (c, n))
    L += ["", "## Spoken, by speaker", "", "| Speaker | Words |", "|---|---|"]
    for c, n in per_speaker.most_common():
        L.append("| %s | %d |" % (c, n))
    L += ["", "## Spoken, by scene", "", "| Scene | Words |", "|---|---|"]
    for c, n in per_scene:
        L.append("| %s | %d |" % (c, n))
    L += ["", "## Diegetic paper, by scene", "", "| Scene | Words |", "|---|---|"]
    for c, n in paper_scene:
        L.append("| %s | %d |" % (c, n))
    io.open(os.path.join(ROOT, "_Word Count.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("spoken %d / %d   paper %d" % (spoken, SPOKEN_LOCK, paper))

if __name__ == "__main__":
    main()
