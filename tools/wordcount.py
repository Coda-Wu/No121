# -*- coding: utf-8 -*-
"""Count the spoken and diegetic-paper budgets in 70-Script/.

Spoken lines are `**SPEAKER:** text` in files with `type: script`.
Everything else - italic stage directions, HTML comments, prose - is free.
Files with `type: document` are counted separately as diegetic paper.

The script is written in Chinese, which has no word boundaries, so the
PRIMARY unit is the Han character. English words are reported alongside
for the localisation side; a mixed line contributes to both honestly.
See the Round 12 amendment in 60-Production/Scope Ledger.md.

Run from the vault root:  python tools/wordcount.py
Writes 70-Script/_Word Count.md
"""
import io, os, re, sys, collections

ROOT = "70-Script"
ZH_FLOOR = 10000          # target volume, Han characters
EN_CEILING = 15000        # the original lock, English words
ZH_PER_EN = 1.6           # working ratio for equivalent content
ZH_CEILING = int(EN_CEILING * ZH_PER_EN)

HAN = re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]")

def strip(t):
    t = re.sub(r"<!--.*?-->", " ", t, flags=re.S)
    return t.replace("\U0001F527", " ")

def han(t):
    return len(HAN.findall(strip(t)))

def en(t):
    """Latin-script words only. Han runs are stripped first so a mixed
    line is not double-counted as one giant 'word'."""
    t = HAN.sub(" ", strip(t))
    t = re.sub(r"[\u3000-\u303f\uff00-\uffef]", " ", t)   # CJK punctuation
    return len([w for w in re.split(r"\s+", t.strip()) if re.search(r"[A-Za-z]", w)])

def main():
    per_scene, per_card, per_speaker = [], collections.Counter(), collections.Counter()
    paper_scene, paper_card = [], collections.Counter()
    for dp, _, fns in os.walk(ROOT):
        for fn in sorted(fns):
            if not fn.endswith(".md") or fn.startswith("_"):
                continue
            p = os.path.join(dp, fn)
            s = io.open(p, encoding="utf-8").read()
            fm = re.match(r"^---\n(.*?)\n---\n", s, re.S)
            meta, body = (fm.group(1), s[fm.end():]) if fm else ("", s)
            kind = (re.search(r"^type:\s*(\S+)", meta, re.M) or [None, "script"])[1]
            card = (re.search(r'card:\s*"([^"]*)"', meta) or [None, "?"])[1]
            card = card if isinstance(card, str) else "?"
            label = os.path.basename(dp) + " / " + fn[:-3]
            if kind == "document":
                b = re.sub(r"<!--.*?-->", " ", body, flags=re.S)
                b = re.sub(r"^\*.*?\*$", " ", b, flags=re.M)
                z, e = han(b), en(b)
                paper_scene.append((label, z, e)); paper_card[card] += z
            else:
                z = e = 0
                for m in re.finditer(r"^\*\*([^*:：]+)[:：]\*\*(.*)$", body, re.M):
                    zc, ec = han(m.group(2)), en(m.group(2))
                    z += zc; e += ec; per_speaker[m.group(1).strip()] += zc
                per_scene.append((label, z, e)); per_card[card] += z
    zh = sum(z for _, z, _ in per_scene)
    ep = sum(e for _, _, e in per_scene)
    pz = sum(z for _, z, _ in paper_scene)
    pe = sum(e for _, _, e in paper_scene)

    L = ["---", "type: report", "status: generated", "---",
         "# Word Count", "",
         "> [!warning] Generated by `tools/wordcount.py`. **Never hand-edit.** Rerun to refresh.", "",
         "The script is written in Chinese. The counted unit is the **Han character**;",
         "English words are shown alongside for localisation. Working ratio: **%.1f Han characters per English word**." % ZH_PER_EN, "",
         "## Totals", "",
         "| Budget | Han chars | Floor | Ceiling | EN words |", "|---|---|---|---|---|",
         "| **Spoken** | %d | %d | %d | %d |" % (zh, ZH_FLOOR, ZH_CEILING, ep),
         "| **Diegetic paper** | %d | — | 🔧 unset | %d |" % (pz, pe), "",
         "- Spoken against the floor: **%d / %d** (%+d)" % (zh, ZH_FLOOR, zh - ZH_FLOOR),
         "- Spoken against the ceiling: **%d / %d** (%+d)" % (zh, ZH_CEILING, zh - ZH_CEILING),
         "- Ceiling in English-word equivalents: **%d / %d**" % (int(round(zh / ZH_PER_EN)) + ep, EN_CEILING), "",
         "## Spoken, by card", "", "| Card | Han chars |", "|---|---|"]
    for c, n in per_card.most_common():
        L.append("| %s | %d |" % (c, n))
    L += ["", "## Spoken, by speaker", "", "| Speaker | Han chars |", "|---|---|"]
    for c, n in per_speaker.most_common():
        L.append("| %s | %d |" % (c, n))
    L += ["", "## Spoken, by scene", "", "| Scene | Han chars | EN words |", "|---|---|---|"]
    for c, z, e in per_scene:
        L.append("| %s | %d | %d |" % (c, z, e))
    L += ["", "## Diegetic paper, by scene", "", "| Scene | Han chars | EN words |", "|---|---|---|"]
    for c, z, e in paper_scene:
        L.append("| %s | %d | %d |" % (c, z, e))
    io.open(os.path.join(ROOT, "_Word Count.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("spoken %d han (floor %d, ceiling %d) / %d en   paper %d han" % (zh, ZH_FLOOR, ZH_CEILING, ep, pz))

if __name__ == "__main__":
    main()
